            A Catalyst for Productivity
        </h3>

        <p class="text-gray-600 leading-relaxed">
            The Goldman Sachs report highlights that while Generative AI is a "major disruption," it is primarily a tool for <strong>augmentation</strong>. While two-thirds of current jobs are exposed to some degree of AI automation, most will see their workloads <strong>complemented</strong> by AI rather than replaced by it.
        </p>

        <p class="text-gray-600 leading-relaxed">
            This shift is projected to drive a massive productivity boom—potentially increasing global GDP by <strong>7%</strong> over a ten-year period. The labor market impact will vary significantly by sector; for instance, administrative and legal roles face higher exposure, while physically intensive sectors like construction and maintenance remain largely unaffected.
        </p>

        <p class="text-gray-600 leading-relaxed font-medium">
            Ultimately, the report suggests that the displacement caused by automation is historically offset by the <strong>creation of new occupations</strong> that emerge from the resulting economic growth.
